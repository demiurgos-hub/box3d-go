// ErrMotionStepLimit means the entire requested duration was not simulated.
// The world may already have advanced; callers must fault the enclosing frame.
var ErrMotionStepLimit = errors.New("box3d: motion microstep limit")

// ErrMotionStepPenetration reports an unresolved solid overlap after a microstep.
// No body is individually restored; the caller must reject the entire frame.
var ErrMotionStepPenetration = errors.New("box3d: motion step exceeded penetration bound")

// ErrMotionStepUnsafePath reports motion generated by the solver that was not
// safely bounded by admission. The caller must reject the entire frame.
var ErrMotionStepUnsafePath = errors.New("box3d: solver motion exceeded admitted path")

// MotionPenetrationRoundoff is the float32 classification allowance at the
// solver penetration bound. It never changes query or placement thresholds.
const MotionPenetrationRoundoff float32 = 1e-6

// MotionStepOptions controls opt-in relative-motion collision subdivisions.
// Mesh contact response still follows the solver's authored triangle winding;
// motion admission uses two-sided surfaces conservatively.
type MotionStepOptions struct {
	MaxMicrosteps                       int
	MaxRotation                         float32
	MaxDelta                            float32
	VelocityIterations, RelaxIterations int
	MaxPathRefinements                  int
	// Tolerance is solver admission contact distance, independent of query APIs.
	Tolerance      float32
	MaxPenetration float32
}

// DefaultMotionStepOptions returns bounded motion admission settings.
func DefaultMotionStepOptions() MotionStepOptions {
	return MotionStepOptions{MaxMicrosteps: 2048, MaxRotation: .01, MaxDelta: 1.0 / 240, VelocityIterations: 4, RelaxIterations: 2, MaxPathRefinements: 8192, Tolerance: .001, MaxPenetration: .01}
}

type motionSolverIterations struct{ velocity, relax int }

var motionIterationSettings [MaxWorlds]motionSolverIterations

func motionIterations(w *world) (int, int) {
	s := motionIterationSettings[w.worldId]
	if s.velocity == 0 {
		return solverIterations, solverRelaxIterations
	}
	return s.velocity, s.relax
}

// MotionBodySample is an independently owned body-origin pose/velocity sample.
type MotionBodySample struct {
	Body                            BodyID
	Start, End                      WorldTransform
	LinearVelocity, AngularVelocity Vec3
}

// MotionStepSample retains every microstep's paths, manifolds and events before
// the next ordinary Step overwrites its arrays. Contact handles remain transient.
// Observers run with the world locked and must not mutate it. Returning an error
// aborts after this step. Bodies contains enabled nonstatic bodies only.
type MotionStepSample struct {
	Index                             int
	Delta, StartFraction, EndFraction float32
	Bodies                            []MotionBodySample
	Contacts                          []ContactData
	ContactEvents                     ContactEvents
	SensorEvents                      SensorEvents
	JointEvents                       JointEvents
}

// MotionStepResult reports work actually executed, including partial failed work.
type MotionStepResult struct {
	Microsteps      int
	Elapsed         float32
	PairTests       int
	PathRefinements int
}

type motionForce struct {
	id            BodyID
	force, torque Vec3
}
type motionSolverShape struct {
	shape  *shape
	path   motionPath
	bounds AABB
}
type motionPair struct {
	a, b, childA, triangleA, childB, triangleB int32
	leaf                                       bool
}

func motionPairKey(a, b int32) motionPair {
	if b < a {
		a, b = b, a
	}
	return motionPair{a: a, b: b}
}

func motionLeafKey(a, b int32, fa, fb QueryFeature) motionPair {
	if b < a {
		a, b, fa, fb = b, a, fb, fa
	}
	return motionPair{a, b, fa.ChildIndex, fa.TriangleIndex, fb.ChildIndex, fb.TriangleIndex, true}
}

// StepMotion advances a requested duration using relative-motion casts to admit
// collision microsteps, then the ordinary contact solver supplies all impulses.
// It preserves the original external force/torque across those internal steps.
// This is an opt-in path; upstream Step/recording/default CCD are unchanged.
// No rollback is attempted on failure. The caller must reject its entire frame.
// It is not safe to call concurrently or mutate from observe. This method is not
// a capacity qualification and may reject numerically unresolved trajectories.
func (id WorldID) StepMotion(dt float32, options MotionStepOptions, observe func(MotionStepSample) error) (MotionStepResult, error) {
	w := getUnlockedWorldFromId(id)
	if w == nil || w.recording != nil || !IsValidFloat(dt) || dt <= 0 || options.MaxMicrosteps <= 0 || !IsValidFloat(options.MaxDelta) || options.MaxDelta <= 0 || options.MaxDelta > .05 || options.MaxPathRefinements < 1 || options.MaxPathRefinements > 131072 || options.VelocityIterations < 1 || options.VelocityIterations > 16 || options.RelaxIterations < 1 || options.RelaxIterations > 16 || !IsValidFloat(options.MaxRotation) || options.MaxRotation <= 0 || options.MaxRotation > .25 || !IsValidFloat(options.Tolerance) || options.Tolerance <= 0 || options.Tolerance >= SpeculativeDistance()/4 || !IsValidFloat(options.MaxPenetration) || options.MaxPenetration <= 0 {
		return MotionStepResult{}, ErrMotionCastInvalid
	}
	previousIterations := motionIterationSettings[w.worldId]
	motionIterationSettings[w.worldId] = motionSolverIterations{options.VelocityIterations, options.RelaxIterations}
	defer func() { motionIterationSettings[w.worldId] = previousIterations }()
	var forces []motionForce
	for i := range w.bodies {
		body := &w.bodies[i]
		if body.id == NullIndex || body.setIndex == disabledSet || body.typ == StaticBody {
			continue
		}
		sim := getBodySim(w, body)
		forces = append(forces, motionForce{BodyID{body.id + 1, w.worldId, body.generation}, sim.force, sim.torque})
	}
	result := MotionStepResult{}
	refinementBudget := options.MaxPathRefinements
	initialDepths := map[motionPair]float32{}
	remaining := dt
	// Time bookkeeping keeps the sum of float32 solver deltas exact without
	// changing any pose, velocity or solver arithmetic from float32.
	elapsed := float64(0)
	for remaining > 0 {
		if result.Microsteps >= options.MaxMicrosteps {
			return result, ErrMotionStepLimit
		}
		for _, f := range forces {
			if !f.id.IsValid() {
				return result, ErrMotionCastInvalid
			}
			body := &w.bodies[f.id.Index1-1]
			if body.setIndex == disabledSet {
				return result, ErrMotionCastInvalid
			}
			sim := getBodySim(w, body)
			sim.force = f.force
			sim.torque = f.torque
		}
		h := MinFloat(remaining, options.MaxDelta)
		// Absorb only a rounding-sized remainder into this actual solver step.
		// A separate nanosecond step rescales cached impulses and resets sleep.
		if remaining-h <= 4*fltEpsilon*options.MaxDelta {
			h = remaining
		}
		// Rotation is bounded independently of translational TOI to retain stable
		// changing contact normals and shortest-arc interpolation.
		for _, f := range forces {
			body := &w.bodies[f.id.Index1-1]
			if body.setIndex != awakeSet {
				continue
			}
			sim, state := getBodySim(w, body), getBodyState(w, body)
			speed := mulAdd(Length(state.angularVelocity), remaining, Length(MulMV(sim.invInertiaWorld, sim.torque)))
			if speed > 0 {
				h = MinFloat(h, options.MaxRotation/speed)
			}
		}
		for attempt := 0; ; attempt++ {
			if attempt == 64 {
				return result, ErrMotionCastConvergence
			}
			fraction, pairs, err := motionStepFraction(w, forces, h, options.Tolerance, options.MaxPenetration, initialDepths, result.Microsteps == 0)
			result.PairTests += pairs
			if err != nil {
				return result, fmt.Errorf("box3d: admission microstep %d dt=%g: %w", result.Microsteps, h, err)
			}
			if fraction >= 1 {
				break
			}
			// The solver's semi-implicit acceleration depends on h. Shrinking
			// time without predicting again can overshoot while braking.
			next := h * fraction * (1 - 1e-4)
			if next <= 0 || next >= h {
				return result, ErrMotionCastConvergence
			}
			h = next
		}
		if h <= 0 || !IsValidFloat(h) || remaining-h == remaining {
			return result, ErrMotionCastConvergence
		}
		sample := MotionStepSample{Index: result.Microsteps, Delta: h, StartFraction: result.Elapsed / dt}
		for _, f := range forces {
			sample.Bodies = append(sample.Bodies, MotionBodySample{Body: f.id, Start: f.id.GetTransform()})
		}
		motionInvalidateMovingMeshCaches(w)
		id.Step(h, 1)
		result.Microsteps++
		elapsed += float64(h)
		if h == remaining {
			result.Elapsed = dt
			remaining = 0
		} else {
			result.Elapsed = float32(elapsed)
			remaining = float32(float64(dt) - elapsed)
		}
		sample.EndFraction = result.Elapsed / dt
		for i := range sample.Bodies {
			v := &sample.Bodies[i]
			v.End = v.Body.GetTransform()
			v.LinearVelocity = v.Body.GetLinearVelocity()
			v.AngularVelocity = v.Body.GetAngularVelocity()
		}
		motionCopyEvents(id, &sample)
		pairs, pathErr := motionValidatePaths(w, sample, options.Tolerance, options.MaxPenetration, initialDepths, &refinementBudget)
		result.PairTests += pairs
		result.PathRefinements = options.MaxPathRefinements - refinementBudget
		if observe != nil {
			if err := motionObserve(w, sample, observe); err != nil {
				return result, err
			}
		}
		if pathErr != nil {
			return result, fmt.Errorf("box3d: actual microstep %d dt=%g: %w", result.Microsteps-1, h, pathErr)
		}
		if err := motionCheckPenetration(w, options.MaxPenetration, initialDepths); err != nil {
			return result, err
		}
	}
	return result, nil
}

func motionObserve(w *world, sample MotionStepSample, observe func(MotionStepSample) error) error {
	w.locked = true
	defer func() { w.locked = false }()
	return observe(sample)
}

func motionCheckPenetration(w *world, limit float32, initialDepths map[motionPair]float32) error {
	for i := range w.contacts {
		c := &w.contacts[i]
		if c.contactId == NullIndex || c.setIndex == disabledSet {
			continue
		}
		a, z := &w.shapes[c.shapeIdA], &w.shapes[c.shapeIdB]
		if w.bodies[a.bodyId].typ != DynamicBody && w.bodies[z.bodyId].typ != DynamicBody {
			continue
		}
		r, ok := (ShapeID{a.id + 1, w.worldId, a.generation}).PairPenetration(ShapeID{z.id + 1, w.worldId, z.generation})
		if !ok {
			return ErrMotionCastUnsupported
		}
		key := motionPairKey(a.id, z.id)
		bound := MaxFloat(limit, initialDepths[key])
		if r.Depth > bound+MotionPenetrationRoundoff {
			return fmt.Errorf("%w: shapes %d/%d depth=%g bound=%g", ErrMotionStepPenetration, a.id, z.id, r.Depth, bound)
		}
		// Existing overlap can recover; its accepted depth may only decrease.
		if initialDepths[key] > r.Depth {
			initialDepths[key] = r.Depth
		}
	}
	return nil
}

func motionPredict(w *world, body *body, dt float32) motionPath {
	sim := getBodySim(w, body)
	q := sim.transform.Q
	c := ToVec3(sim.center)
	start := Transform{c, q}
	end := start
	if state := getBodyState(w, body); state != nil {
		v := MulSV(1/mulAdd(1, dt, sim.linearDamping), state.linearVelocity)
		v = MulAdd(v, dt*sim.invMass, sim.force)
		if sim.invMass > 0 {
			v = MulAdd(v, dt*sim.gravityScale, w.gravity)
		}
		angular := MulSV(1/mulAdd(1, dt, sim.angularDamping), state.angularVelocity)
		angular = MulAdd(angular, dt, MulMV(sim.invInertiaWorld, sim.torque))
		if state.flags&lockLinearX != 0 {
			v.X = 0
		}
		if state.flags&lockLinearY != 0 {
			v.Y = 0
		}
		if state.flags&lockLinearZ != 0 {
			v.Z = 0
		}
		if state.flags&lockAngularX != 0 {
			angular.X = 0
		}
		if state.flags&lockAngularY != 0 {
			angular.Y = 0
		}
		if state.flags&lockAngularZ != 0 {
			angular.Z = 0
		}
		if Length(v) > w.maxLinearSpeed {
			v = MulSV(w.maxLinearSpeed/Length(v), v)
		}
		end = Transform{MulAdd(c, dt, v), integrateRotation(q, MulSV(dt, angular))}
	}
	path := newMotionPath(start, end)
	path.center = sim.localCenter
	return path
}

func motionStepFraction(w *world, bodies []motionForce, dt, tolerance, limit float32, initialDepths map[motionPair]float32, initial bool) (float32, int, error) {
	var moving []motionSolverShape
	for _, f := range bodies {
		body := &w.bodies[f.id.Index1-1]
		path := motionPredict(w, body, dt)
		for index := body.headShapeId; index != NullIndex; index = w.shapes[index].nextShapeId {
			s := &w.shapes[index]
			if s.sensorIndex != NullIndex {
				continue
			}
			moving = append(moving, motionSolverShape{s, path, motionBounds(path, motionShapeRadius(s, path.center), SpeculativeDistance())})
		}
	}
	return motionEvaluatePairs(w, moving, dt, tolerance, initialDepths, initial, limit, false, nil)
}

func motionValidatePaths(w *world, sample MotionStepSample, tolerance, limit float32, initialDepths map[motionPair]float32, budget *int) (int, error) {
	var moving []motionSolverShape
	for _, v := range sample.Bodies {
		body := &w.bodies[v.Body.Index1-1]
		center := getBodySim(w, body).localCenter
		start, end := ToRelativeTransform(v.Start, Pos{}), ToRelativeTransform(v.End, Pos{})
		start.P = Add(start.P, RotateVector(start.Q, center))
		end.P = Add(end.P, RotateVector(end.Q, center))
		path := newMotionPath(start, end)
		path.center = center
		for index := body.headShapeId; index != NullIndex; index = w.shapes[index].nextShapeId {
			s := &w.shapes[index]
			if s.sensorIndex == NullIndex {
				moving = append(moving, motionSolverShape{s, path, motionBounds(path, motionShapeRadius(s, center), tolerance)})
			}
		}
	}
	_, pairs, err := motionEvaluatePairs(w, moving, sample.Delta, tolerance, initialDepths, false, limit, true, budget)
	return pairs, err
}

func motionEvaluatePairs(w *world, moving []motionSolverShape, dt, tolerance float32, initialDepths map[motionPair]float32, initial bool, limit float32, validate bool, budget *int) (float32, int, error) {
	sort.Slice(moving, func(i, j int) bool {
		if moving[i].bounds.LowerBound.X != moving[j].bounds.LowerBound.X {
			return moving[i].bounds.LowerBound.X < moving[j].bounds.LowerBound.X
		}
		return moving[i].shape.id < moving[j].shape.id
	})
	fraction := float32(1)
	pairs := 0
	var failure error
	test := func(a, z motionSolverShape) {
		if failure != nil || a.shape.bodyId == z.shape.bodyId || !a.bounds.Overlaps(z.bounds) {
			return
		}
		ba, bz := &w.bodies[a.shape.bodyId], &w.bodies[z.shape.bodyId]
		if ba.typ != DynamicBody && bz.typ != DynamicBody || !shouldShapesCollide(a.shape.filter, z.shape.filter) || !shouldBodiesCollide(w, ba, bz) {
			return
		}
		if w.customFilterFcn != nil && ((a.shape.flags|z.shape.flags)&uint8(enableCustomFiltering)) != 0 {
			if !w.customFilterFcn(ShapeID{a.shape.id + 1, w.worldId, a.shape.generation}, ShapeID{z.shape.id + 1, w.worldId, z.shape.generation}, w.customFilterContext) {
				return
			}
		}
		pairs++
		if initial {
			r, ok := (ShapeID{a.shape.id + 1, w.worldId, a.shape.generation}).PairPenetration(ShapeID{z.shape.id + 1, w.worldId, z.shape.generation})
			if !ok {
				failure = ErrMotionCastUnsupported
				return
			}
			if r.Depth > 0 {
				initialDepths[motionPairKey(a.shape.id, z.shape.id)] = r.Depth
			}
		}
		// Recenter before GJK and conservative advancement, including COM paths.
		base := a.path.start.P
		ma, mb := a.path, z.path
		ma.start.P = Sub(ma.start.P, base)
		ma.end.P = Sub(ma.end.P, base)
		mb.start.P = Sub(mb.start.P, base)
		mb.end.P = Sub(mb.end.P, base)
		velocity := Sub(Sub(mb.end.P, mb.start.P), Sub(ma.end.P, ma.start.P))
		ra, rb := motionShapeRadius(a.shape, ma.center), motionShapeRadius(z.shape, mb.center)
		// Admission targets actual contact, using tolerance only to stop early.
		// Public queries instead sweep the entire expanded tolerance band.
		_, failure = motionVisitShapeMotion(a.shape, z.shape, ma, mb, ToPos(base), tolerance, true, false, func(r MotionCastResult, la, lb queryLeaf) error {
			key := motionLeafKey(a.shape.id, z.shape.id, r.FeatureA, r.FeatureB)
			if initial && r.Initial {
				initialDepths[key] = r.Depth
			} else if initialDepths[key] > r.Depth {
				initialDepths[key] = r.Depth
			}
			angular := float32(ma.angle*ra*Length(Cross(RotateVector(ma.start.Q, ma.axis), r.Normal))) + float32(mb.angle*rb*Length(Cross(RotateVector(mb.start.Q, mb.axis), r.Normal)))
			closing := MaxFloat(0, -Dot(velocity, r.Normal)) + angular
			bound := MaxFloat(limit, initialDepths[key])
			if validate {
				depthBound := mulAdd(r.Depth, 1-r.Fraction, closing)
				if depthBound > bound+MotionPenetrationRoundoff {
					if r.Initial && r.Depth > bound+MotionPenetrationRoundoff {
						return ErrMotionStepPenetration
					}
					if err := motionCertifyLeafPath(la, lb, ma, mb, 0, .5, tolerance, bound, budget, 0); err != nil {
						return err
					}
					return motionCertifyLeafPath(la, lb, ma, mb, .5, 1, tolerance, bound, budget, 0)
				}
				return nil
			}
			travel := Length(velocity) + float32(ma.angle*ra) + float32(mb.angle*rb)
			if r.Fraction*travel > 0.25*SpeculativeDistance() {
				fraction = MinFloat(fraction, r.Fraction)
			} else if closing > 0 {
				budget := MinFloat(0.25*SpeculativeDistance(), .5*(bound-r.Depth))
				if budget <= 0 {
					// An initial overlap at its inherited bound must still get a
					// solver opportunity to recover; postvalidation forbids growth.
					budget = .01 * limit
				}
				fraction = MinFloat(fraction, budget/closing)
			}
			return nil
		})
	}
	for i, a := range moving {
		for j := i + 1; j < len(moving) && moving[j].bounds.LowerBound.X <= a.bounds.UpperBound.X; j++ {
			test(a, moving[j])
		}
		if w.bodies[a.shape.bodyId].typ != DynamicBody {
			continue
		}
		w.broadPhase.trees[StaticBody].Query(a.bounds, DefaultMaskBits, false, func(_ int, data uint64, _ any) bool {
			s := &w.shapes[int(int32(data))]
			if s.sensorIndex != NullIndex {
				return true
			}
			body := &w.bodies[s.bodyId]
			path := motionPredict(w, body, dt)
			test(a, motionSolverShape{s, path, computeFatShapeAABB(s, getBodyTransformQuick(w, body), SpeculativeDistance())})
			return failure == nil
		}, nil)
	}
	return fraction, pairs, failure
}

func motionInvalidateMovingMeshCaches(w *world) {
	for i := range w.contacts {
		c := &w.contacts[i]
		if c.contactId == NullIndex || c.flags&simMeshContact == 0 || w.bodies[c.edges[0].bodyId].typ == StaticBody {
			continue
		}
		// Upstream stores the triangle query region in WORLD coordinates and
		// otherwise reuses it while only B stays inside. A moving mesh changes
		// which triangles occupy that region even if a passive B did not move.
		c.meshContact.queryBounds = AABB{Vec3{fltMax, fltMax, fltMax}, Vec3{-fltMax, -fltMax, -fltMax}}
		c.flags &^= relativeTransformValid
	}
}

func motionCopyEvents(id WorldID, sample *MotionStepSample) {
	c := id.GetContactEvents()
	c.BeginEvents = append([]ContactBeginTouchEvent(nil), c.BeginEvents...)
	c.EndEvents = append([]ContactEndTouchEvent(nil), c.EndEvents...)
	c.HitEvents = append([]ContactHitEvent(nil), c.HitEvents...)
	sample.ContactEvents = c
	s := id.GetSensorEvents()
	s.BeginEvents = append([]SensorBeginTouchEvent(nil), s.BeginEvents...)
	s.EndEvents = append([]SensorEndTouchEvent(nil), s.EndEvents...)
	sample.SensorEvents = s
	j := id.GetJointEvents()
	j.JointEvents = append([]JointEvent(nil), j.JointEvents...)
	sample.JointEvents = j
	seen := map[ContactID]bool{}
	for _, body := range sample.Bodies {
		contacts := make([]ContactData, body.Body.GetContactCapacity())
		n := body.Body.GetContactData(contacts)
		for _, contact := range contacts[:n] {
			if seen[contact.ContactId] {
				continue
			}
			seen[contact.ContactId] = true
			contact.Manifolds = append([]Manifold(nil), contact.Manifolds...)
			sample.Contacts = append(sample.Contacts, contact)
		}
	}
}
